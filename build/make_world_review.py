"""Write the world bank as a review document in redesign/."""
import json
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from residue.worldgen import load_bank  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "redesign", "Worlds_v2_Review_2026-10-30.md")


def main():
    bank = load_bank(os.path.join(HERE, "worlds", "bank.jsonl"), with_meta=True)
    assign = json.load(open(os.path.join(HERE, "worlds", "assignment.json")))
    ver = set(assign["verification"])
    log = [json.loads(l) for l in open(os.path.join(HERE, "worlds", "draft_log.jsonl"))]
    rejected = [r for r in log if not r["accepted"]]
    flagged = [w.world_id for w, m in bank if m.get("flagged")]
    attempts = Counter(r["world_id"] for r in log)

    kinds = Counter(tuple(sorted(x["kind"] for x in m["disputes"])) for _, m in bank)
    kind_single = Counter(x["kind"] for _, m in bank for x in m["disputes"])
    n_sources = Counter(len(m["sources"]) for _, m in bank)
    core_pos = Counter(int(w.core.pid[1:]) for w, _ in bank)
    names = Counter(n for _, m in bank for n in m.get("names", []))
    repeated = {n: c for n, c in names.items() if c > 1}
    words = Counter()
    for w, m in bank:
        for wd in set(re.findall(r"\b[A-Z][a-z]{3,}\b", " ".join(m.get("names", [])))):
            words[wd] += 1
    stems = {k: v for k, v in words.most_common() if v >= 3}
    openers = Counter(p.text.split()[0] for w, _ in bank for p in w.propositions)

    lines = ["# World Bank, Version 2: For Review", "",
             "Generated by Claude, 2026-10-30, from `build/worlds/bank.jsonl`. Version 1 is archived in `build/worlds/v1/` "
             "and reviewed in `GPT Review of World Bank v1 (2026-10-30)`. Seventy fictional events, five per event type, "
             "drafted by Claude Sonnet 5.5 and checked by GPT-6.1 Terra.",
             "",
             "## What changed from version 1", "",
             "- The v1 schema marked conflicts with a 0/1 field, which the drafter read as member order in nine worlds, pairing a cause with a count. "
             "Each dispute is now an explicit object holding its two claims, with a kind and a short statement of what is in dispute, so pair membership cannot be mislabeled.",
             "- Each world declares a closed list of four to six sources, and every sentence's source must be on it. This is checked mechanically, as are 15 background facts, "
             "two disputes of different kinds, distinct sources within each dispute, no duplicate sentences, and at least four sentences with numbers.",
             "- The drafting prompt follows GPT's replacement text, with these changes: the explicit dispute objects, a dispute kind, a list of invented names already used in other worlds that the drafter must not reuse, "
             "and the reasons for rejection when a draft is redrafted.",
             "- Every draft that passes the mechanical checks is read by a checker from a different model family (GPT-6.1 Terra at high reasoning effort). For every sentence it judges "
             "whether the source could know it and whether it favors a dispute claim. It also judges whether each dispute's claims share a referent, are incompatible, and are balanced, "
             "and it looks for inconsistencies and real referents. Any defect sends the draft back with the reasons, up to four attempts. A world with no clean attempt keeps its "
             "attempt with the fewest defects and is flagged below.",
             "- Sentence order is shuffled with a seed derived from the world ID, so the core and the disputes do not sit at fixed positions.",
             "- Twenty-four worlds had no draft that passed the checker within four attempts. Each was repaired in place: the drafter received its best draft and the "
             "checker's defects, changed only the sentences named, and the checker re-read the result (`build/repair_worlds.py`, logged in `worlds/repair_log.jsonl`). "
             "Twenty passed. Claude edited the remaining four by hand, along with W011, whose time dispute set two devices' records against each other, which the checker had passed. "
             "Every hand edit is logged with its before and after text in `worlds/hand_edits.jsonl`, and the checker re-read each edited world. Repaired and hand-edited worlds are marked below.",
             "",
             "## Bank-wide diagnostics", "",
             f"- Drafting attempts in the log: {len(log)}, {len(rejected)} rejected. The log includes entries for W000 to W011 from an overlapping run that was stopped (see the build README); the bank's drafts are identified by matching text. Attempts per world: "
             + ", ".join(f"{k} attempt(s): {v} worlds" for k, v in sorted(Counter(attempts.values()).items())) + ".",
             f"- Worlds still flagged after repair and hand editing: {', '.join(flagged) if flagged else 'none'}.",
             "- Sources per world: " + ", ".join(f"{k}: {v}" for k, v in sorted(n_sources.items())) + ".",
             "- Dispute kinds, counted over all 140 disputes: " + ", ".join(f"{k} {v}" for k, v in kind_single.most_common()) + ".",
             "- Dispute kind combinations: " + ", ".join(f"{' + '.join(k)} {v}" for k, v in kinds.most_common()) + ".",
             "- Core position (proposition index): " + ", ".join(f"{k}: {v}" for k, v in sorted(core_pos.items())) + ".",
             f"- Invented names used in more than one world: {', '.join(f'{n} ({c})' for n, c in sorted(repeated.items())) if repeated else 'none'}.",
             f"- Name words in three or more worlds: {', '.join(f'{n} ({c})' for n, c in stems.items()) if stems else 'none'}.",
             "- Most common first words of sentences, over 1,400: " + ", ".join(f"{w} {c}" for w, c in openers.most_common(8)) + ".",
             "",
             f"Verification worlds (marked V below, never used in the main analyses): {', '.join(sorted(ver))}.",
             "",
             "## Questions for reviewers", "",
             "1. Is each dispute a genuine incompatibility about one referent, such that a careful writer could not report both claims as true, and is neither claim obviously right?",
             "2. Does any background fact or the core settle a dispute?",
             "3. Could every source observe or document what is attributed to it?",
             "4. Do the worlds vary enough, within and across event types, that a classifier cannot learn the drafting template instead of structure?",
             "5. Does any world contain real organizations, people, places, or incidents, or content a model might refuse to write about?",
             "",
             "## The worlds", "",
             "Each world shows its source list, its disputes with sources, and then every sentence in the order writers receive it.", ""]
    for w, m in bank:
        tag = " (V)" if w.world_id in ver else ""
        flag = (" FLAGGED" if m.get("flagged") else "") + (" (repaired)" if m.get("repaired") else "") + \
            (f" (hand edited: {', '.join(m['hand_edited'])})" if m.get("hand_edited") else "")
        by = w.by_id()
        lines += [f"### {w.world_id}{tag}{flag}: {w.event_type}", "", f"Sources: {'; '.join(m['sources'])}.", ""]
        for i, (a, b) in enumerate(w.conflict_pairs()):
            d = m["disputes"][i]
            lines.append(f"Dispute {i + 1} ({d['kind']}, {d['about']}): {a}, {by[a].text} ({by[a].source}) VERSUS {b}, {by[b].text} ({by[b].source})")
            lines.append("")
        if m.get("check_problems"):
            lines += ["Checker defects on the kept attempt: " + " | ".join(m["check_problems"]), ""]
        pairs = {pid: i + 1 for i, pr in enumerate(w.conflict_pairs()) for pid in pr}
        lines += ["| # | Fact | Source | Role |", "|---|---|---|---|"]
        for p in w.propositions:
            role = "core" if p.core else (f"dispute {pairs[p.pid]}" if p.pid in pairs else "")
            lines.append(f"| {p.pid} | {p.text.replace('|', '/')} | {p.source} | {role} |")
        lines.append("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.abspath(OUT), "|", len(bank), "worlds | flagged:", flagged)


if __name__ == "__main__":
    main()
