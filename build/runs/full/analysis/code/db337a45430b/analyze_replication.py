"""Analysis of the fresh-seed replication (runs/replication/PLAN.md).

    python analyze_replication.py

Rebuilds the replication's results from runs/replication/calls.jsonl
without calls, fits the comparisons in the plan on the new replicates only,
with the full run's folds, learners, and refitted permutations, and writes
runs/replication/analysis.md and .json.
"""
import json
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analyze  # noqa: E402
import inference  # noqa: E402
import replicate  # noqa: E402
import run  # noqa: E402
from residue import adapters  # noqa: E402
from residue import analysis as an  # noqa: E402
from residue.embed import Embedder  # noqa: E402
from residue.features import body  # noqa: E402
from residue.store import CallStore  # noqa: E402

REP = os.path.join(HERE, "runs", "replication")
COMPARISONS = [  # (positive class second, as in the full run: control, then structure B)
    ("D0", "NC0", "control", {"features": 499, "embedding": 199}),
    ("NULL-a", "NULL-b", "control", {"features": 499, "embedding": 199}),
    ("D0", "NULL-a", "control", {"features": 199, "embedding": 199}),
    ("SD-same", "SI-same", "p2", {"features": 999, "embedding": 199}),
]
LABEL = {"NULL-a": "pure null, first draw (NULL-a)", "NULL-b": "pure null, second draw (NULL-b)"}


def nm(c):
    return LABEL.get(c) or analyze.name(c)


def load():
    worlds = run.load_worlds("full")
    store = CallStore(os.path.join(REP, "calls.jsonl"))
    m = adapters.make(run.PRIMARY, None, role="producer", max_output_tokens=run.max_tokens("incident", run.PRIMARY))
    models = {(run.PRIMARY, "incident"): run.Frozen(m)}
    control, hub = replicate.plan(worlds)
    rows, timing, failures = [], [], {}
    for blocks in (control, hub):
        results, f, errors = run.run_blocks(blocks, store, models, 16)
        failures.update(f)
        assert not errors, errors
        for bid, res in results.items():
            _, wid, rep = bid.split("|")
            for cond, nodes in res.items():
                t = nodes[replicate.TERMINAL[cond]]
                rows.append(dict(world=wid, rep=int(rep), cond=cond, text=t.text, time=store.records[t.key]["time"]))
    rows.sort(key=lambda r: (r["world"], r["rep"], r["cond"]))
    by = {(r["world"], r["rep"], r["cond"]): r for r in rows}
    for (wid, rep, cond), r in by.items():
        if cond == "D0" and (wid, rep, "NC0") in by:
            timing.append(by[(wid, rep, "NC0")]["time"] - r["time"])
    return rows, timing, failures


def main():
    t0 = time.time()
    rows, timing, failures = load()
    fo = analyze.folds()
    embed = Embedder(run.EMBED_CACHE)
    J = {"rows": len(rows), "timing": {"pairs": len(timing), "control_later": int(sum(1 for d in timing if d > 0)),
                                       "median_gap_s": float(np.median(timing))}, "results": {}}
    for a, b, kind, perms in COMPARISONS:
        sub = [r for r in rows if r["cond"] in (a, b)]
        y = np.array([[a, b].index(r["cond"]) for r in sub])
        w = [r["world"] for r in sub]
        groups = [(r["world"], r["rep"]) for r in sub]
        for lrn, n in perms.items():
            X = np.asarray(embed.many([body(r["text"]) for r in sub]) if lrn == "embedding"
                           else analyze.text_X([r["text"] for r in sub]), float)
            level = 0.90 if kind == "control" else 0.95
            res, _ = analyze.fit(X, y, w, fo, level)
            perm = inference.permutation(X, y, w, groups, fo, n, f"replication|{a}|{b}|{lrn}")
            out = {"auc": res["auc"], "lo": res["lo"], "hi": res["hi"], "level": level, "n": len(y), **perm}
            if kind == "control":
                out["verdict"] = an.three_way(res["lo"], res["hi"], 0.43, 0.57)
            J["results"][f"{a}|{b}|{lrn}"] = out
            print(f"[{time.time() - t0:.0f}s] {a} {b} {lrn} auc {res['auc']:.3f} p_up {perm['p_upper']:.3f} "
                  f"p2 {perm['p_two_sided']:.3f}", flush=True)
    with open(os.path.join(REP, "analysis.json"), "w") as fh:
        json.dump(J, fh, indent=1)

    full = json.load(open(os.path.join(analyze.OUT, "inference.json")))["perm"]
    tm = J["timing"]
    L = ["# Replication of the direct-report control and hub against diamond", "",
         f"Generated by `analyze_replication.py` at {time.strftime('%Y-%m-%d %H:%M')} from `runs/replication/calls.jsonl`, "
         "following `PLAN.md`, which was written before the run. Primary producer gemini-3.5-flash-lite, incident genre, "
         "the 60 full-run worlds, new replicates 3 to 5 with fresh keys and seeds. These are new generations from the same "
         "worlds and templates, not new worlds, and the replication was motivated by the full run's control result. "
         "Models are trained and tested on the new replicates only, with the full run's world-grouped folds and learners. "
         "Permutations swap labels within each world and replicate and refit everything, as in `inference.md`.", "",
         f"Execution order: the control was generated after the direct report in {tm['control_later']} of {tm['pairs']} "
         f"pairs (full run: 169 of 180), median gap {tm['median_gap_s']:.0f} s. Failed trials: {json.dumps(failures) if failures else 'none'}.", "",
         "## Controls and the pure null", "",
         "AUC with two-sided 90% world-bootstrap intervals, three-way verdict at the 0.43 to 0.57 tolerance, and refitted "
         "permutation p-values. The second-named class is the positive class.", "",
         "| Comparison | Learner | AUC [90%] | Verdict | Permutations | One-sided p | Two-sided p | Full run AUC |",
         "|---|---|---|---|---|---|---|---|"]
    for a, b, kind, perms in COMPARISONS:
        if kind != "control":
            continue
        for lrn in perms:
            v = J["results"][f"{a}|{b}|{lrn}"]
            f = full.get(f"{a}|{b}|{lrn}")
            L.append(f"| {nm(a)} against {nm(b)} | {lrn} | {v['auc']:.3f} [{v['lo']:.3f}, {v['hi']:.3f}] | {v['verdict']} | "
                     f"{v['n_perm']} | {v['p_upper']:.3f} | {v['p_two_sided']:.3f} | {f['auc']:.3f} |" if f else
                     f"| {nm(a)} against {nm(b)} | {lrn} | {v['auc']:.3f} [{v['lo']:.3f}, {v['hi']:.3f}] | {v['verdict']} | "
                     f"{v['n_perm']} | {v['p_upper']:.3f} | {v['p_two_sided']:.3f} | not run |")
    L += ["", "## Hub against diamond (P2)", "",
          "AUC with 95% world-bootstrap intervals and refitted one-sided permutation p (AUC above the null), hub as the "
          "positive class.", "",
          "| Learner | AUC [95%] | Permutations | One-sided p | Full run AUC | Full run one-sided p |", "|---|---|---|---|---|---|"]
    for lrn in ("features", "embedding"):
        v = J["results"][f"SD-same|SI-same|{lrn}"]
        f = full[f"SD-same|SI-same|{lrn}"]
        L.append(f"| {lrn} | {v['auc']:.3f} [{v['lo']:.3f}, {v['hi']:.3f}] | {v['n_perm']} | {v['p_upper']:.3f} | "
                 f"{f['auc']:.3f} | {f['p_upper']:.3f} |")
    L += ["", f"Rows: {J['rows']}. Run time {time.time() - t0:.0f} s.", ""]
    with open(os.path.join(REP, "analysis.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", os.path.join(REP, "analysis.md"))


if __name__ == "__main__":
    main()
