"""Two post hoc checks raised by the manuscript review of 2026-11-02.

    python analyze_review_checks.py

Makes no model calls. Writes runs/full/analysis/review_checks.md and .json.

1. Single reports without shared texts. Stored outputs are shared across
   structures by design (the independent, out-star, and Y sets of a block
   contain the same report 1, and the Y set's reports 2 and 3 equal the
   out-star's report 2 and the independent set's report 3). A single-report
   model therefore meets identical texts under different labels, which pushes
   the single-report diagnostic toward chance by construction. This check
   uses only texts that appear in one of the two compared structures:
   reports 2 and 3 of the independent and out-star sets, which are never
   shared between those two structures. Feature and embedding learners,
   world-grouped folds, as in analyze.py.

2. Unsupervised similarity scores. AUC of a single relational statistic
   (minimum, median, or maximum over the three pairs of each pairwise
   similarity), with no training, for independent against out-star, by
   producer. Rarity tables are fit per outer fold on the training worlds with
   each row's own world removed, as in the canonical pipeline.
"""
import json
import os
import sys
import time
from itertools import combinations

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analyze  # noqa: E402
import run  # noqa: E402
from residue import analysis as an  # noqa: E402
from residue.embed import Embedder  # noqa: E402
from residue.features import WorldRarity, body, pair_features, sentences  # noqa: E402

OUT = analyze.OUT


def main():
    t0 = time.time()
    _, _, s2, _ = analyze.load()
    fo = analyze.folds()
    embed = Embedder(run.EMBED_CACHE)
    J = {"single_unshared": {}, "unsupervised": {}}
    for prod in run.PRODUCERS:
        rows = [r for r in s2 if r["producer"] == prod and r["access"] == "full" and r["arm"] == "neutral"
                and r["structure"] in ("IND", "DEP")]
        # 1. reports 2 and 3 only
        texts = [r["texts"][j] for r in rows for j in (1, 2)]
        y = np.array([["IND", "DEP"].index(r["structure"]) for r in rows for _ in (1, 2)])
        w = [r["world"] for r in rows for _ in (1, 2)]
        shared = len(set(t for r in rows if r["structure"] == "IND" for t in r["texts"][1:]) &
                     set(t for r in rows if r["structure"] == "DEP" for t in r["texts"][1:]))
        Xf = np.asarray(analyze.text_X(texts), float)
        Xe = np.asarray(embed.many([body(t) for t in texts]), float)
        out = {"n_reports": len(texts), "texts_shared_between_structures": shared}
        for name, X in (("features", Xf), ("embedding", Xe)):
            P, _ = an.oof_predict(X, y, w, fo)
            out[name] = an.auc_with_ci(y, P, w, n=analyze.NBOOT, level=0.90)
            lo, hi = out[name]["lo"], out[name]["hi"]
            out[name]["verdict"] = an.three_way(lo, hi, 0.43, 0.57)
        J["single_unshared"][prod] = out
        # 2. unsupervised scores, IND = 0, DEP = 1 (higher similarity predicts DEP)
        yS = np.array([["IND", "DEP"].index(r["structure"]) for r in rows])
        wS = [r["world"] for r in rows]
        embed.many([body(t) for r in rows for t in r["texts"]] + [s for r in rows for t in r["texts"] for s in sentences(t)])
        fold_of = np.array([fo[r["world"]] for r in rows])
        stats = {}
        for f in sorted(set(fold_of)):
            rar = WorldRarity.from_rows([r for r, fv in zip(rows, fold_of) if fv != f])
            for i in np.flatnonzero(fold_of == f):
                r = rows[i]
                pf = [pair_features(a, b, rar.for_world(r["world"]), embed) for a, b in combinations(r["texts"], 2)]
                for k in pf[0]:
                    vals = sorted(p[k] for p in pf)
                    for agg, v in (("min", vals[0]), ("median", vals[1]), ("max", vals[2])):
                        stats.setdefault(f"{k}_{agg}", np.zeros(len(rows)))[i] = v
        J["unsupervised"][prod] = {k: an.auc_with_ci(yS, v, wS, n=analyze.NBOOT) for k, v in sorted(stats.items())}
        print(f"[{time.time() - t0:.0f}s] {prod}", flush=True)
    with open(os.path.join(OUT, "review_checks.json"), "w") as fh:
        json.dump(J, fh, indent=1, default=float)

    def ci(x):
        return f"{x['auc']:.3f} [{x['lo']:.3f}, {x['hi']:.3f}]"
    L = ["# Post hoc checks from the manuscript review, full run", "",
         f"Generated by `analyze_review_checks.py` at {time.strftime('%Y-%m-%d %H:%M')}. No model calls. Full access, neutral "
         "attribution, independent (IND) against out-star (DEP). Both checks were added after the results were known, in "
         "response to the 2026-11-02 review.", "",
         "## Single reports, unshared texts only", "",
         "Reports 2 and 3 of each independent and out-star set, which never coincide between the two structures. AUC with "
         "90% world-cluster intervals, equivalence band 0.43 to 0.57.", "",
         "| Producer | Reports | Texts shared between structures | Features | Embedding |", "|---|---|---|---|---|"]
    for p, o in J["single_unshared"].items():
        L.append(f"| {p} | {o['n_reports']} | {o['texts_shared_between_structures']} | {ci(o['features'])} ({o['features']['verdict']}) | "
                 f"{ci(o['embedding'])} ({o['embedding']['verdict']}) |")
    L += ["", "## Unsupervised similarity scores", "",
          "AUC of each statistic used directly as a score (higher means out-star), no training, 95% world-cluster intervals.", ""]
    keys = list(next(iter(J["unsupervised"].values())))
    L += ["| Statistic | " + " | ".join(J["unsupervised"]) + " |", "|---" * (len(J["unsupervised"]) + 1) + "|"]
    for k in keys:
        L.append(f"| {k} | " + " | ".join(ci(J["unsupervised"][p][k]) for p in J["unsupervised"]) + " |")
    L += ["", f"Run time {time.time() - t0:.0f} s."]
    with open(os.path.join(OUT, "review_checks.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote review_checks.md")


if __name__ == "__main__":
    main()
