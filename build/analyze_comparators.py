"""Stronger comparison models for the set result, as fixed in
runs/full/analysis/stronger_comparators_PLAN.md.

    python analyze_comparators.py

No model calls. Independent against out-star, full access, neutral arm: all
three producers after one rewrite (rebuilt from runs/full/calls.jsonl),
Gemini after five rewrites (runs/depth/sets.jsonl), and Haiku after three
(runs/depth_haiku/sets.jsonl) if present. Writes
runs/full/analysis/stronger_comparators.md and .json.
"""
import json
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analyze  # noqa: E402
import run  # noqa: E402
from analyze_depth import oof_by_fold, pooled_X, relational_by_fold  # noqa: E402
from analyze_secondary import gb_oof  # noqa: E402
from residue import analysis as an  # noqa: E402
from residue.embed import Embedder  # noqa: E402
from residue.features import body  # noqa: E402

OUT = analyze.OUT
NBOOT = analyze.NBOOT


def rich_X(rows):
    """Mean, minimum, maximum, and standard deviation of each per-report feature over the set's three reports."""
    out = []
    for r in rows:
        F = np.asarray(analyze.text_X(r["texts"]), float)
        out.append(np.concatenate([F.mean(0), F.min(0), F.max(0), F.std(0)]))
    return np.array(out)


def embed_X(rows, embed):
    """Mean and per-dimension standard deviation of the three report embeddings."""
    out = []
    for r in rows:
        E = np.asarray(embed.many([body(t) for t in r["texts"]]), float)
        out.append(np.concatenate([E.mean(0), E.std(0)]))
    return np.array(out)


def compare(rows, fo, embed):
    rows = sorted([r for r in rows if r["structure"] in ("IND", "DEP")], key=lambda r: (r["world"], r["rep"], r["structure"]))
    y = np.array([1 if r["structure"] == "DEP" else 0 for r in rows])
    w = [r["world"] for r in rows]
    X0, XR, XE = pooled_X(rows), rich_X(rows), embed_X(rows, embed)
    P = {"pooled": an.oof_predict(X0, y, w, fo)[0][:, 1],
         "pooled_rich": an.oof_predict(XR, y, w, fo)[0][:, 1],
         "pooled_boosted": gb_oof(XR, y, w, fo)[:, 1],
         "embedding_set": an.oof_predict(XE, y, w, fo)[0][:, 1]}
    fold_of, Xr_by = relational_by_fold(rows, X0, fo, embed)
    P["relational"] = oof_by_fold(fold_of, Xr_by, y, w, fo)[:, 1]
    Pg = np.zeros(len(y))
    for f, (_, Xr) in Xr_by.items():
        pf = gb_oof(Xr, y, w, fo)[:, 1]
        Pg[fold_of == f] = pf[fold_of == f]
    P["relational_boosted"] = Pg
    res = {"n": len(y), "auc": {k: an.auc_with_ci(y, v, w, n=NBOOT) for k, v in P.items()}}
    nonrel = ("pooled", "pooled_rich", "pooled_boosted", "embedding_set")
    res["relational_minus"] = {k: an.paired_delta_auc(y, P["relational"], P[k], w, n=NBOOT) for k in nonrel}
    best = max(nonrel, key=lambda k: res["auc"][k]["auc"])
    res["best_nonrelational"] = best
    res["relational_boosted_minus_relational"] = an.paired_delta_auc(y, P["relational_boosted"], P["relational"], w, n=NBOOT)
    return res


def main():
    t0 = time.time()
    fo = analyze.folds()
    embed = Embedder(run.EMBED_CACHE)
    _, _, s2, _ = analyze.load()
    S = {}
    for p in run.PRODUCERS:
        S[f"{p}|1"] = [r for r in s2 if r["producer"] == p and r["access"] == "full" and r["arm"] == "neutral"]
    for name, path, d in (("gemini-3.5-flash-lite", os.path.join(HERE, "runs", "depth", "sets.jsonl"), 5),
                          ("claude-haiku-5-5", os.path.join(HERE, "runs", "depth_haiku", "sets.jsonl"), 3)):
        if os.path.exists(path):
            S[f"{name}|{d}"] = [r for r in (json.loads(l) for l in open(path, encoding="utf-8")) if r["depth"] == d]
    J = {}
    for key, rows in S.items():
        J[key] = compare(rows, fo, embed)
        print(f"[{time.time() - t0:.0f}s] {key}", flush=True)
    with open(os.path.join(OUT, "stronger_comparators.json"), "w") as fh:
        json.dump(J, fh, indent=1, default=float)

    def ci(x, k="auc"):
        return f"{x[k]:.3f} [{x['lo']:.3f}, {x['hi']:.3f}]"
    names = ["pooled", "pooled_rich", "pooled_boosted", "embedding_set", "relational", "relational_boosted"]
    L = ["# Stronger comparison models for the set result", "",
         f"Generated by `analyze_comparators.py` at {time.strftime('%Y-%m-%d %H:%M')}. Plan: `stronger_comparators_PLAN.md`. "
         "Independent against out-star, full access, neutral arm. AUC with 95% world-cluster intervals.", "",
         "| Producer, rewrites | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
    for key, r in J.items():
        L.append(f"| {key.replace('|', ', ')} | " + " | ".join(ci(r["auc"][n]) for n in names) + " |")
    L += ["", "## Paired differences", "",
          "| Producer, rewrites | Relational minus pooled | minus pooled rich | minus pooled boosted | minus embedding set | Best non-relational | Relational boosted minus relational |",
          "|---|---|---|---|---|---|---|"]
    for key, r in J.items():
        m = r["relational_minus"]
        L.append(f"| {key.replace('|', ', ')} | " + " | ".join(ci(m[k], "delta") for k in ("pooled", "pooled_rich", "pooled_boosted", "embedding_set"))
                 + f" | {r['best_nonrelational']} | {ci(r['relational_boosted_minus_relational'], 'delta')} |")
    L += ["", f"Run time {time.time() - t0:.0f} s."]
    with open(os.path.join(OUT, "stronger_comparators.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
